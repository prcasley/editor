// Writes a property's facts.md from its facts.json and what the build produced, so
// the prose can never drift from the numbers the scenes were built with.
import { basisOf, type Fact, type Facts } from './facts'
import type { SceneOutput } from './types'

export type SceneCheck = {
  output: SceneOutput
  nodeCount: number
  nodeTypes: Record<string, number>
  validateScene: { valid: boolean; errors: number; warnings: number }
  verifyScene: { hasIssues: boolean; issues: string[] }
  buildJson: { ok: boolean; errors: number; warnings: number }
  toolCalls: Record<string, number>
}

const esc = (v: string) => v.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function valueText(f: Fact): string {
  return f.unit ? `${f.value} ${f.unit}` : String(f.value)
}

function basisText(facts: Facts, f: Fact): string {
  const cite = (f.sources ?? []).map((id) => {
    const s = facts.file.sources.find((x) => x.id === id)!
    return `[${s.publisher}, ${s.date}](${s.url})`
  })
  switch (basisOf(f)) {
    case 'estimate':
      return `**Estimate.** ${f.estimate}`
    case 'derived':
      return `Derived from ${cite.join('; ')}: ${f.derivation}`
    default:
      return `${cite.join('; ')}: ${f.quote}`
  }
}

export function renderFactsMd(facts: Facts, slug: string, checks: SceneCheck[]): string {
  const F = facts.file
  const entries = Object.entries(F.facts)
  const row = ([, f]: [string, Fact]) =>
    `| ${esc(f.label)} | ${esc(valueText(f))} | ${esc(basisText(facts, f))} |`
  const sourced = entries.filter(([, f]) => basisOf(f) !== 'estimate')
  const estimated = entries.filter(([, f]) => basisOf(f) === 'estimate')
  const lines: string[] = [
    `# ${F.name}`,
    '',
    `<!-- Generated by examples/woodmont-portfolio/build.ts from ${slug}/facts.json. Edit the JSON and rebuild. -->`,
    '',
    `**Type:** ${F.type}  `,
    `**Location:** ${F.location}`,
    '',
    F.summary,
    '',
    '## Scenes',
    '',
  ]
  for (const c of checks) {
    lines.push(
      `### ${c.output.title}: \`${c.output.file}\``,
      '',
      '| | |',
      '|---|---|',
      ...Object.entries(c.output.stats).map(([k, v]) => `| ${esc(k)} | ${esc(String(v))} |`),
      `| Scene nodes | ${c.nodeCount} (${Object.entries(c.nodeTypes)
        .sort((a, b) => b[1] - a[1])
        .map(([t, n]) => `${n} ${t}`)
        .join(', ')}) |`,
      `| Pascal MCP tool calls | ${Object.values(c.toolCalls).reduce((a, b) => a + b, 0)} (${Object.entries(
        c.toolCalls,
      )
        .map(([t, n]) => `${t} ${n}`)
        .join(', ')}) |`,
      `| \`validate_scene\` | ${c.validateScene.valid ? 'valid' : 'INVALID'}, ${c.validateScene.errors} errors, ${c.validateScene.warnings} warnings |`,
      `| \`verify_scene\` | ${c.verifyScene.hasIssues ? c.verifyScene.issues.map(esc).join('; ') : 'no issues'} |`,
      `| Editor "Load build" check (\`validateBuildJson\`) | ${c.buildJson.ok ? 'ok' : 'FAILED'}, ${c.buildJson.errors} errors, ${c.buildJson.warnings} warnings |`,
      '',
      ...(c.output.notes ?? []).map((n) => `${n}\n`),
    )
  }
  lines.push(
    '## Facts from public sources',
    '',
    '| Fact | Value | Source |',
    '|---|---|---|',
    ...sourced.map(row),
    '',
    '## Estimates',
    '',
    'Each of these is a modelling assumption, not a published number.',
    '',
    '| Assumption | Value | Why |',
    '|---|---|---|',
    ...estimated.map(row),
    '',
  )
  const unused = facts.unused()
  if (unused.length > 0) {
    lines.push(
      'Facts listed above but not used to shape the scene (context only): ',
      unused.map((k) => F.facts[k]!.label).join(', '),
      '',
    )
  }
  if (F.notes?.length) lines.push('## Conflicts and notes', '', ...F.notes.map((n) => `- ${n}`), '')
  if (F.images?.length) {
    lines.push(
      '## Reference images',
      '',
      'Referenced by URL only; the images belong to Woodmont Properties and their publishers and are not stored in this repository.',
      '',
      ...F.images.map((i) => `- [${i.caption}](${i.url}) (credit: ${i.credit})`),
      '',
    )
  }
  lines.push(
    '## Sources',
    '',
    ...F.sources.map((s) => `- ${s.publisher}, "${s.title}", ${s.date}. <${s.url}>`),
    '',
  )
  return lines.join('\n')
}
