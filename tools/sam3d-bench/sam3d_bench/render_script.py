"""Write a bash script that renders every Pascal case's image.png, one at a time.

Rendering is slow (minutes per image on SwiftShader) and the harness is shared, so the
script runs sequentially, skips cases that already have an image, and takes case ids as
arguments to render a subset:

    python -m sam3d_bench.render_script --cases cases --out render-cases.sh
    RENDERER=/path/to/render.mjs BASE=http://127.0.0.1:5391/ ./render-cases.sh [case_id ...]
"""

from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

from .case_format import find_cases

HEADER = """#!/usr/bin/env bash
# Generated by: python -m sam3d_bench.render_script. Renders Pascal cases sequentially.
# RENDERER: path to the harness render.mjs; BASE: URL of the harness dev server.
set -u
: "${RENDERER:?set RENDERER to the harness render.mjs}"
: "${BASE:=http://127.0.0.1:5391/}"
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$(dirname "$RENDERER")"
want=" $* "
fail=0
render() {  # case_id width height query
  local dir="$HERE/cases/$1"
  if [ "$want" != "  " ] && [[ "$want" != *" $1 "* ]]; then return 0; fi
  if [ -s "$dir/image.png" ]; then echo "skip $1 (image.png exists)"; return 0; fi
  echo "render $1"
  # Playwright picks the format from the extension, so the temp name must end in .png.
  local tmp="$dir/image.tmp.png"
  rm -f "$tmp"
  timeout 1500 node "$RENDERER" --base "$BASE" --q "$4" --w "$2" --h "$3" \\
    --out "$tmp" --timeout 300000 --settle 3000 --log "$dir/render.log" > "$dir/render.out" 2>&1
  local status=$?
  if [ "$status" -eq 0 ] && [ -s "$tmp" ]; then
    mv "$tmp" "$dir/image.png"; tail -1 "$dir/render.out"
  else
    echo "FAILED $1 (exit $status; see $dir/render.out)"; rm -f "$tmp"; fail=1
  fi
}
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m sam3d_bench.render_script", description=__doc__.split("\n")[0])
    ap.add_argument("--cases", required=True, type=Path, help="cases root (render-request.json per case)")
    ap.add_argument("--out", required=True, type=Path, help="script path; must sit next to the cases folder")
    args = ap.parse_args(argv)
    if args.out.resolve().parent != args.cases.resolve().parent or args.cases.name != "cases":
        raise SystemExit("--out must be next to a folder named 'cases' (the script resolves cases/ beside it)")
    lines = [HEADER]
    count = 0
    for d in find_cases(args.cases):
        req_path = d / "render-request.json"
        if not req_path.is_file():
            continue
        req = json.loads(req_path.read_text())
        lines.append(f"render {shlex.quote(d.name)} {int(req['width'])} {int(req['height'])} "
                     f"{shlex.quote(req['query'])}")
        count += 1
    lines.append('exit "$fail"\n')
    args.out.write_text("\n".join(lines))
    args.out.chmod(0o755)
    print(f"wrote {args.out} with {count} render commands")
    return 0 if count else 1


if __name__ == "__main__":
    sys.exit(main())
